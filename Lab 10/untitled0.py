# Lab 10: Survival Analysis
# Kaplan-Meier and Log-Rank Test
# Load the heart failure readmission dataset

import pandas as pd
import matplotlib.pyplot as plt
from lifelines import KaplanMeierFitter
from lifelines.statistics import logrank_test

readmission_data = pd.read_csv("km_logrank_readmission (1).csv")

print(readmission_data.head())
print(readmission_data.info())

# Lab 10 - Kaplan-Meier Survival Analysis
# Compare hospital readmission between treatment groups.

km_model = KaplanMeierFitter()
plt.figure(figsize=(10, 6))

# Plot each treatment group's readmission-free survival curve.
for group_name, group_data in readmission_data.groupby("treatment_group"):
    km_model.fit(
        durations=group_data["time_days"],
        event_observed=group_data["readmitted"],
        label=group_name
    )
    km_model.plot_survival_function()

# Perform the log-rank test.
standard = readmission_data[
    readmission_data["treatment_group"] == "Standard care"
]
telehealth = readmission_data[
    readmission_data["treatment_group"] == "Telehealth follow-up"
]

result = logrank_test(
    standard["time_days"],
    telehealth["time_days"],
    event_observed_A=standard["readmitted"],
    event_observed_B=telehealth["readmitted"]
)

plt.title("Kaplan-Meier: Heart Failure Readmission")
plt.xlabel("Time After Discharge (Days)")
plt.ylabel("Probability of No Readmission")
plt.xlim(0, 180)
plt.grid(alpha=0.3)
plt.tight_layout()

# Save the figure for GitHub.
plt.savefig("kaplan_meier_logrank.png", dpi=300)
plt.show()

print("Log-rank test p-value:", result.p_value)

# Lab 10: Cox Proportional Hazards Analysis
# Analyze time to all-cause death after heart failure diagnosis.

from lifelines import CoxPHFitter

# Load the second dataset.
cox_data = pd.read_csv("cox_ph_heart_failure_survival (1).csv")

# Remove patient IDs because they are not predictors.
cox_data = cox_data.drop(columns=["patient_id"])

# Convert the remaining variables to numeric values.
# Convert sex from text to numeric values.
cox_data["sex"] = cox_data["sex"].map({"Female": 0, "Male": 1})

# Convert all remaining columns to numeric values.
cox_data = cox_data.apply(pd.to_numeric)

# Fit the Cox proportional hazards model.
cox_model = CoxPHFitter()

cox_model.fit(
    cox_data,
    duration_col="time_months",
    event_col="death"
)

# Display the statistical results.
cox_model.print_summary()

# Create and save the hazard ratio figure.
plt.figure(figsize=(10, 7))
cox_model.plot(hazard_ratios=True)
plt.title("Cox Proportional Hazards: Heart Failure Survival")
plt.xlabel("Hazard Ratio")
plt.tight_layout()
plt.savefig("cox_proportional_hazards.png", dpi=300, bbox_inches="tight")
plt.show()